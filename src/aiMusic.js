export function getMoodSongs(mood) {
  const data = moods[mood];
  if (!data) return [];

  const songs = Array.from({ length: 100 }, (_, i) => ({
    id: `${mood}-${i + 1}`,
    title: `${data.titles[i % data.titles.length]} ${String(i + 1).padStart(3, '0')}`,
    lyrics: data.lyrics[i % data.lyrics.length],
    audioUrl: ''
  }));

  setSongs(songs);
  return songs;
}
