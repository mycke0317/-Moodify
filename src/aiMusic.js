const songs = Object.entries(moods).flatMap(([mood, data]) => {
  return Array.from({ length: 100 }, (_, index) => {
    const group = Math.floor(index / 10);
    const position = index % 10;

    const title = data.titles[group];

    const verse1 = data.verses[position];
    const verse2 = data.verses[(position + group + 1) % 10];
    const chorus = data.choruses[(position + group) % 10];
    const ending = data.choruses[(position + group + 3) % 10];

    return {
      id: `${mood}-${index + 1}`,
      title: `${title} ${position + 1}`,
      mood,
      moodName: data.name,
      lyrics: [
        '[Verse 1]',
        verse1,
        verse2,
        '',
        '[Chorus]',
        chorus,
        ending,
        '',
        '[Verse 2]',
        data.verses[(position + 3) % 10],
        data.verses[(position + 6) % 10],
        '',
        '[Final Chorus]',
        data.choruses[(position + 5) % 10],
        data.choruses[(position + 7) % 10]
      ].join('\n'),
      audioUrl: null
    };
  });
});

export function getMoodSongs(mood) {
  return songs.filter(song => song.mood === mood);
}

export function getAllMoodSongs() {
  return songs;
}

export function getMoodName(mood) {
  return moods[mood]?.name ?? '알 수 없음';
}
